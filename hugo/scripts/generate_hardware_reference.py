#!/usr/bin/env python3
"""Generate a source-level EtherCAT entry catalogue; --check detects stale pages.

This deliberately does not execute IOC shell scripts or expand configuration
macros. Conditional entries and includes remain visible as source definitions.
Only the Python standard library is required.
"""
import argparse
from collections import defaultdict
from pathlib import Path
import re
from urllib.parse import quote

ROOT = Path(__file__).resolve().parents[2]
OUTPUT = ROOT / 'hugo/content/manual/knowledgebase/hardware/entries'
SOURCE = 'https://github.com/paulscherrerinstitute/ecmccfg/blob/master/'
MARKER = '<!-- Generated by hugo/scripts/generate_hardware_reference.py; do not edit. -->'
CALL = re.compile(r'Cfg\.(EcAddEntryDT|EcAddEntryComplete|EcAddEntryAlias|EcAddDataDT|EcAddMemMapDT)\(')


def split_arguments(text):
    """Split commas outside nested macros/expressions; return at closing )."""
    args, start, depth = [], 0, 0
    for index, char in enumerate(text):
        if char in '({':
            depth += 1
        elif char == ')' and depth == 0:
            return args + [text[start:index].strip()]
        elif char in ')}':
            depth -= 1
        elif char == ',' and depth == 0:
            args.append(text[start:index].strip())
            start = index + 1
    raise ValueError('Unterminated entry declaration: ' + text)


def direction(value):
    return {'1': 'Output (master → slave)', '2': 'Input (slave → master)'}.get(value, value)


def declarations(source):
    entries = []
    for number, line in enumerate(source.splitlines(), 1):
        if line.lstrip().startswith('#'):
            continue
        for match in CALL.finditer(line):
            kind = match.group(1)
            try:
                args = split_arguments(line[match.end():])
            except ValueError:
                entries.append(dict(line=number, name='Unparsed declaration', kind=kind,
                                    condition='Check source syntax', datatype='Parse warning',
                                    direction='—', address=line.strip()))
                continue
            condition = line[:match.start()].split('ecmcConfig', 1)[0].strip()
            entry = dict(line=number, name=args[-1], kind=kind,
                         condition=condition or '—', datatype='—', direction='—', address='—')
            if kind in ('EcAddEntryDT', 'EcAddEntryComplete'):
                expected = (10, 11)
                if len(args) not in expected:
                    raise ValueError(f'{kind}: unexpected arguments on line {number}: {args}')
                datatype = args[8]
                if kind == 'EcAddEntryDT':
                    entry['name'] = args[9]
                    if len(args) == 11:
                        datatype += '; update=' + args[10]
                if kind == 'EcAddEntryComplete':
                    datatype += ' bits'
                    if len(args) == 11 and args[9] in ('0', '1'):
                        datatype += '; signed=' + args[9]
                    elif len(args) == 11:
                        entry['name'] = args[9]
                        datatype += '; update=' + args[10] + ' (legacy unsigned)'
                    else:
                        datatype += ' (legacy)'
                entry.update(datatype=datatype, direction=direction(args[3]),
                             address=f'{args[6]}:{args[7]} (PDO {args[5]}, SM {args[4]})')
            elif kind == 'EcAddEntryAlias':
                if len(args) != 3:
                    raise ValueError(f'{kind}: unexpected arguments: {args}')
                entry['address'] = 'Alias of ' + args[1]
            elif kind == 'EcAddDataDT':
                if len(args) != 6:
                    raise ValueError(f'{kind}: unexpected arguments: {args}')
                entry.update(datatype=args[4], direction=direction(args[3]),
                             address=f'{args[0]}; byte {args[1]}, bit {args[2]}')
            elif kind == 'EcAddMemMapDT':
                if len(args) != 5:
                    raise ValueError(f'{kind}: unexpected arguments: {args}')
                entry.update(datatype=args[3], direction=direction(args[2]),
                             address=f'{args[0]}; bytes {args[1]}')
            entries.append(entry)
    return entries


def page_name(directory):
    return directory.as_posix().replace('/', '--').lower() + '.md'


def anchor(path):
    return 'snippet-' + path.stem.lower()


def reference(path):
    page = page_name(path.parent)
    return '{{< relref "/manual/knowledgebase/hardware/entries/' + page + '#' + anchor(path) + '" >}}'


def code(value):
    # Escape pipes even inside code spans so Markdown tables stay intact.
    return '`' + value.replace('|', '&#124;').replace('`', '&#96;') + '`'


def render(root=ROOT):
    sources = {path.relative_to(root / 'hardware'): path.read_text()
               for path in sorted((root / 'hardware').rglob('*'))
               if path.suffix in ('.cmd', '.iocsh')}
    by_name = defaultdict(list)
    for path in sources:
        by_name[path.name].append(path)
    entries, includes = {}, {}
    for path, source in sources.items():
        try:
            entries[path] = declarations(source)
        except ValueError as error:
            raise ValueError(f'hardware/{path}: {error}') from error
        related = set()
        for line in source.splitlines():
            if line.lstrip().startswith('#') or not re.search(r'SCRIPTEXEC|iocshLoad', line):
                continue
            # Match literal filenames after macro prefixes as well as paths.
            for name in re.findall(r'[A-Za-z0-9_][A-Za-z0-9_.-]*\.(?:cmd|iocsh)', line):
                related.update(by_name.get(name, []))
        includes[path] = related - {path}
    selected = {path for path in sources if entries[path]}
    while True:
        expanded = selected | {path for path in sources if includes[path] & selected}
        if selected == expanded:
            break
        selected = expanded
    groups = defaultdict(list)
    for path in sorted(selected):
        groups[path.parent].append(path)

    index = [
        '+++', 'title = "Hardware entry reference"', 'weight = 17', '+++', '', MARKER, '',
        'This catalogue is generated from the hardware scripts. It lists EtherCAT entry',
        'identifiers such as `positionActual01` (the exact spelling matters), their',
        'data types, directions, PDO addresses, aliases and process-image data items.',
        'Choose a hardware family below, then find the slave or snippet by filename.', '',
        'An entry is referenced in configuration/PLC code as',
        '`ec<master>.s<slave>.<entry>`, for example `ec0.s2.positionActual01`.',
        'These identifiers are distinct from EPICS PV names such as `Enc01-PosAct`;',
        'database templates determine which entries also have PVs.', '',
        '## Options and shared snippets', '',
        'This is a **source reference**, not the effective mapping of a running IOC.',
        'Macros such as `${CH_ID}` and `${KEY=positionActual}` are retained as written.',
        'The condition column shows the command prefix used to enable or comment out',
        'an entry. Follow its source link for the option logic and defaults.',
        'All conditional branches are listed; they are not necessarily active together.',
        'Shared hardware scripts are linked separately rather than expanded with guessed',
        'channel numbers or option values. Dynamic include filenames must be resolved',
        'from the configuration. Scripts containing only SDO settings are not listed.',
        'Malformed declarations are retained as parse warnings with source links;',
        'their presence in this catalogue does not mean that the script is supported',
        'or that its mapping has been validated on hardware.',
        'An entry name alone does not establish its physical meaning or scaling:',
        'check the selected options and device-specific article, especially for raw',
        'versus scaled feedback on the [Nanotec N6]({{< relref "/manual/knowledgebase/hardware/Nanotec-N6_OPT.md" >}}).', '',
        '## Hardware families', '',
        '| Family / directory | Scripts and snippets | Entry declarations |',
        '| --- | --- | --- |',
    ]
    pages = {}
    for group, paths in sorted(groups.items()):
        filename = page_name(group)
        title = group.as_posix()
        index.append(f'| [{title}](' + '{{< relref "/manual/knowledgebase/hardware/entries/' + filename + '" >}}' + f') | {len(paths)} | {sum(len(entries[p]) for p in paths)} |')
        body = ['+++', f'title = "{title}"', '+++', '', MARKER, '',
                'Entry declarations below are shown as written, before macro expansion.',
                'Conditional entries require the corresponding options. See the',
                '[reference guide]({{< relref "/manual/knowledgebase/hardware/entries/_index.md" >}})',
                'for naming, direction and inclusion rules.', '', '## Scripts and snippets', '']
        body.extend(f'- [{path.name}](#{anchor(path)})' for path in paths)
        for path in paths:
            source_url = SOURCE + quote('hardware/' + path.as_posix(), safe='/')
            body.extend(['', f'<a id="{anchor(path)}"></a>', '', '## ' + path.name, '',
                         f'[Source: hardware/{path}]({source_url})', ''])
            params = re.findall(r'^\s*#-d\s+\\param\s+(.+)$', sources[path], re.MULTILINE)
            if params:
                body.extend(['Documented configuration options:', ''])
                body.extend('- ' + param for param in params)
                body.append('')
            related = sorted(includes[path] & selected)
            if related:
                body.extend(['Referenced hardware snippets (may be conditional):', ''])
                body.extend(f'- [{p}]({reference(p)})' for p in related)
                body.append('')
            if not entries[path]:
                body.append('No direct entry declarations; follow the referenced snippets above.')
                continue
            body.extend(['| Entry identifier | Type | Direction | Object / data source | Condition prefix | Source |',
                         '| --- | --- | --- | --- | --- | --- |'])
            for entry in entries[path]:
                cells = [code(entry['name']), code(entry['datatype']), entry['direction'],
                         code(entry['address']), code(entry['condition']),
                         f'[L{entry["line"]}]({source_url}#L{entry["line"]})']
                body.append('| ' + ' | '.join(cells) + ' |')
        pages[filename] = '\n'.join(line.rstrip() for line in body).rstrip() + '\n'
    index.extend(['', '## Keeping this reference current', '',
                  'After changing a hardware script, run:', '', '```bash',
                  'python3 hugo/scripts/generate_hardware_reference.py', '```', '',
                  'Commit the generated pages with the script change. The Hugo CI workflow',
                  'runs the generator with `--check` and rejects stale pages. No EtherCAT',
                  'hardware, EPICS installation or external Python packages are required.', ''])
    pages['_index.md'] = '\n'.join(index)
    return pages


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--check', action='store_true')
    args = parser.parse_args()
    pages = render()
    stale = []
    for name, expected in pages.items():
        path = OUTPUT / name
        if not path.exists() or path.read_text() != expected:
            stale.append(name)
            if not args.check:
                path.parent.mkdir(parents=True, exist_ok=True)
                path.write_text(expected)
    for path in sorted(OUTPUT.glob('*.md')):
        if path.name not in pages and MARKER in path.read_text():
            stale.append(path.name)
            if not args.check:
                path.unlink()
    if args.check and stale:
        parser.exit(1, 'Stale hardware entry reference; run python3 hugo/scripts/generate_hardware_reference.py:\n' + '\n'.join(stale) + '\n')
    print(f'Hardware entry reference: {len(pages)} pages ' + ('are current.' if args.check else 'generated.'))


if __name__ == '__main__':
    main()
